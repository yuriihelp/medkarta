export function getWeekData(week: number): WeekData {
  const data = PREGNANCY_WEEKS.find(w => w.week === week)
  return data ?? PREGNANCY_WEEKS[PREGNANCY_WEEKS.length - 1]
}

/** Calculate current pregnancy week from LMP date */
export function calcPregnancyWeek(lmpDate: Date): { week: number; day: number } {
  const diff = Math.floor((Date.now() - lmpDate.getTime()) / (1000 * 60 * 60 * 24))
  const week = Math.floor(diff / 7)
  const day = diff % 7
  return { week: Math.max(1, Math.min(week, 40)), day }
}
